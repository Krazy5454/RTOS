void PM_handler()
{
  static int i = 0;
  //do thing
  while(!PM_FIFO_full(0))
  {
    PM_set_duty_absolute(0, sineLookupTable[i]);
    i++;
    if (i >= SIN_WAVE_SIZE)
      i = 0;
  }
}

